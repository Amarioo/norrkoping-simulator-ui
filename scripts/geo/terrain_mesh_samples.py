"""Step 3 regression fixture src/lib/geo/terrain-mesh-control.json.

* `native`: random positions (continuous coordinates, not the pixel centres the mesh was refined on)
  per group, with the native Lantmäteriet 1 m DTM height there (bilinear between pixel centres) and
  the rendered height of the previous 10 m / 40 m mesh (`before`) for the report.
* `mesh`: positions with the mesh height computed by the reference implementation scripts/geo/rtin.py,
  which surfaceMesh.ts and TerrainService.kt must reproduce.
* `limits`: per group, the measured accuracy of the active mesh plus a small margin (regression bound).

Usage: python scripts/geo/terrain_mesh_samples.py   (after scripts/prepare-terrain-mesh.py --activate)
"""
import base64, json, math, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'work/geodata/python'))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import numpy as np
import rtin
import terrain_mesh_study as study

GROUPS = {'road': 1500, 'path': 800, 'railCorridor': 800, 'tramStreet': 400, 'building': 800, 'riverbank': 1000,
          'builtUpLand': 1500, 'centralLand': 1000, 'urban': 600, 'open': 1500, 'water': 800, 'steepLand': 800,
          'testArea': 1500, 'testAreaRoads': 800}


def main():
    terrain = rtin.read(ROOT / 'src/lib/data/terrain.json')
    mesh = terrain['mesh']
    tile, g = rtin.load_grid(terrain)
    layout = rtin.Layout(tile, mesh['depth'])
    assert (layout.columns, layout.rows) == (mesh['columns'], mesh['rows'])
    bits = np.frombuffer(base64.b64decode(mesh['activeBase64']), np.uint8)
    active = np.unpackbits(bits, bitorder='little')[:layout.columns * layout.rows].astype(bool).reshape(layout.rows, layout.columns)
    hn = layout.node_heights(g)
    ref = terrain['reference']; unit = ref['metresPerUnit'] * ref['gridScaleFactor']
    city = rtin.read(ROOT / 'src/lib/data/norrkoping-map.json')
    native, info = study.mosaic(ref, city['meta']['bounds'])
    cats = study.categories(ref, info, city)
    b = city['meta']['bounds']
    rng = np.random.default_rng(20261018)
    n = 6_000_000
    x = rng.uniform(b[0], b[2], n); z = rng.uniform(b[1], b[3], n)
    E = ref['originEasting'] + x * unit; N = ref['originNorthing'] - z * unit
    col = E - info['left'] - .5; row = info['top'] - N - .5
    c0 = np.floor(col).astype(int); r0 = np.floor(row).astype(int); tx = col - c0; tz = row - r0
    a = np.asarray(native)
    dtm = (a[r0, c0] * (1 - tx) * (1 - tz) + a[r0, c0 + 1] * tx * (1 - tz) + a[r0 + 1, c0] * (1 - tx) * tz
           + a[r0 + 1, c0 + 1] * tx * tz)
    ri, ci = np.round(row).astype(int), np.round(col).astype(int)
    pc = study.with_built_up(np.asarray(cats)[ri, ci], np.asarray(study.built_up(cats))[ri, ci])
    test = (E >= study.TEST_BOX[0]) & (E <= study.TEST_BOX[2]) & (N >= study.TEST_BOX[1]) & (N <= study.TEST_BOX[3])
    gx = (x - layout.x0) / layout.step; gz = (z - layout.z0) / layout.step
    masks = study.groups(x, z, pc, np.zeros(n, bool), test)
    # Slope from the native DTM at the sample's pixel (central differences, 1 m pixels).
    slope =np.hypot((a[r0, np.minimum(c0 + 1, a.shape[1] - 1)] - a[r0, np.maximum(c0 - 1, 0)]) / 2,
                     (a[np.minimum(r0 + 1, a.shape[0] - 1), c0] - a[np.maximum(r0 - 1, 0), c0]) / 2)
    masks['steepLand'] = masks['land'] & (slope > .3)
    cls = study.error_class(pc)
    masks['builtUpLand'] = masks['land'] & ((pc & study.BITS['builtUp']) > 0)
    masks['urban'] = cls == study.CLASSES.index('urban')
    masks['open'] = cls == study.CLASSES.index('open')
    masks['water'] = cls == study.CLASSES.index('water')
    ok = np.isfinite(dtm)
    out = {'note': 'Native Lantmäteriet 1 m DTM (bilinear between pixel centres, RH2000 metres) at random '
                   'positions; `before` = previous 10 m / 40 m mesh; generated by '
                   'scripts/geo/terrain_mesh_samples.py.', 'native': [], 'mesh': [], 'limits': {}, 'summary': {}}
    for group, count in GROUPS.items():
        idx = np.flatnonzero(masks[group] & ok)
        pick = rng.choice(idx, size=min(count, len(idx)), replace=False)
        after, _ = rtin.leaf_heights(layout, active, gx[pick], gz[pick], hn)
        before = study.current_surface(tile, g, x[pick], z[pick])
        for i, h0 in zip(pick, before):
            out['native'].append({'group': group, 'x': round(float(x[i]), 5), 'z': round(float(z[i]), 5),
                                  'dtm': round(float(dtm[i]), 3), 'before': round(float(h0), 3)})
        # Errors of the rounded fixture, as the test computes them.
        d = np.array([e['dtm'] for e in out['native'][-len(pick):]])
        ea = after - d; eb = before - d
        s = lambda e: {'mean': round(float(e.mean()), 3), 'rmse': round(float(np.sqrt((e ** 2).mean())), 3),
                       'p95': round(float(np.percentile(np.abs(e), 95)), 3), 'max': round(float(np.abs(e).max()), 2)}
        out['summary'][group] = {'n': len(pick), 'before': s(eb), 'after': s(ea)}
        up = lambda v: math.ceil(v * 100) / 100
        out['limits'][group] = {'mean': up(abs(float(ea.mean())) + .05), 'rmse': up(float(np.sqrt((ea ** 2).mean())) * 1.15 + .01),
                                'p95': up(float(np.percentile(np.abs(ea), 95)) * 1.15 + .01)}
    # Reference mesh heights at 3000 positions (a third of them in the test area).
    pick = np.concatenate([rng.choice(np.flatnonzero(ok), 2000, replace=False),
                           rng.choice(np.flatnonzero(ok & test), 1000, replace=False)])
    h, _ = rtin.leaf_heights(layout, active, gx[pick], gz[pick], hn)
    out['mesh'] = [[round(float(x[i]), 6), round(float(z[i]), 6), round(float(v), 6)] for i, v in zip(pick, h)]
    # Reproduce with the rounded positions (the test reads the rounded values).
    xr = np.array([m[0] for m in out['mesh']]); zr = np.array([m[1] for m in out['mesh']])
    h, _ = rtin.leaf_heights(layout, active, (xr - layout.x0) / layout.step, (zr - layout.z0) / layout.step, hn)
    # Two independent leaf searches (level geometry and bisection) must agree.
    for xi, zi, hi in zip(xr, zr, h):
        d = rtin.descend(layout, active, hn, (xi - layout.x0) / layout.step, (zi - layout.z0) / layout.step)
        assert abs(d - hi) < 1e-9, (xi, zi, d, hi)
    out['mesh'] = [[m[0], m[1], round(float(v), 6)] for m, v in zip(out['mesh'], h)]
    path = ROOT / 'src/lib/geo/terrain-mesh-control.json'
    path.write_text(json.dumps(out, separators=(',', ':')) + '\n', encoding='utf8')
    # The backend (TerrainService.kt) must reproduce the same mesh heights.
    backend = ROOT.parent / 'norrkoping-simulator-backend/src/test/resources/terrain-mesh-control.json'
    backend.parent.mkdir(parents=True, exist_ok=True)
    backend.write_text(json.dumps({'note': 'Mesh heights (metres RH2000) from the UI reference implementation '
                                           'scripts/geo/rtin.py; generated by scripts/geo/terrain_mesh_samples.py.',
                                   'revision': terrain['revision'], 'mesh': out['mesh']},
                                  separators=(',', ':')) + '\n', encoding='utf8')
    print(json.dumps(out['summary'], indent=1))


if __name__ == '__main__':
    main()
