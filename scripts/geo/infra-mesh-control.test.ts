/**
 * Step 5: backend fixture for the rendered surface (TerrainMeshTest.kt). Heights from the UI surface
 * (surfaceMesh.ts, including the road breakline patches) at the Step 3 control positions plus 2 000
 * deterministic positions inside the patch boxes, so TerrainService.kt is checked on patched leaves too.
 * Run after scripts/geo/road_patches.py --apply:
 *   npx vitest run -c scripts/geo/vitest.infra.config.ts scripts/geo/infra-mesh-control.test.ts
 */
import { expect, it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { terrain } from '../../src/lib/terrain';
import control from '../../src/lib/geo/terrain-mesh-control.json';
it('writes the backend surface fixture', () => {
  const M = terrain.data.reference.metresPerUnit,
    O = terrain.data.reference.verticalOriginMetres;
  const metres = (x: number, z: number) => Math.round((terrain.surfaceHeight(x, z) * M + O) * 1e6) / 1e6;
  const points: number[][] = control.mesh.map(([x, z]) => [x, z, metres(x, z)]);
  let seed = 20261019;
  const random = () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648);
  const boxes = Object.values(terrain.data.mesh!.patches?.boxes ?? {});
  for (let i = 0; boxes.length && i < 2000; i++) {
    const [e0, n0, e1, n1] = boxes[i % boxes.length];
    const [x, z] = terrain.fromSweref(e0 + (e1 - e0) * random(), n0 + (n1 - n0) * random());
    points.push([Math.round(x * 1e6) / 1e6, Math.round(z * 1e6) / 1e6, 0]);
    points[points.length - 1][2] = metres(points.at(-1)![0], points.at(-1)![1]);
  }
  expect(points.length).toBeGreaterThan(3000);
  writeFileSync(
    '../norrkoping-simulator-backend/src/test/resources/terrain-mesh-control.json',
    JSON.stringify({
      note: 'Rendered surface heights (metres RH2000) from the UI (surfaceMesh.ts incl. road breakline patches); generated by scripts/geo/infra-mesh-control.test.ts.',
      revision: terrain.data.revision,
      mesh: points,
    }) + '\n',
  );
});
